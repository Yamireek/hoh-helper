let detail=ev('heroDialogMarkup()');
assert.equal((detail.match(/data-revert-kind=/g)||[]).length,4);
assert(detail.includes('data-revert-kind="LEVEL"'));
assert(detail.includes('data-revert-key="weapon"'));
assert(detail.includes('data-revert-key="alexander-weapon"'));
