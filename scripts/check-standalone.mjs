import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('standalone.html','utf8');
const fixtures=fs.readFileSync('src/mock-data.js','utf8').replaceAll('export const ','const ');
const logic=fs.readFileSync('src/main.js','utf8').replace(/^import .*?from '\.\/mock-data\.js';\n/,'');
const css=fs.readFileSync('src/styles.css','utf8');
const match=html.match(/<script>([\s\S]*?)<\/script>/);
assert(match,'Standalone is missing embedded JavaScript');
const embedded=match[1];
assert.equal(embedded,fixtures+'\n'+logic.replaceAll('</script>','<\\/script>'),'Standalone embedded JavaScript incomplete or different from source');
assert(html.includes('<style>'+css+'</style>'),'Standalone CSS incomplete');
assert(html.includes('boot-fallback'),'Boot error fallback missing');
new vm.Script(embedded,{filename:'standalone.html'});
let markup='';
const root={set innerHTML(v){markup=v},get innerHTML(){return markup}};
const document={getElementById:id=>id==='app'?root:null,querySelector:()=>null,querySelectorAll:()=>[],addEventListener:()=>{},createElement:()=>({})};
const storage={getItem(){throw Error('Storage disabled')},setItem(){throw Error('Storage disabled')},removeItem(){throw Error('Storage disabled')}};
vm.runInNewContext(embedded,{document,localStorage:storage,console,structuredClone,setTimeout:()=>0,clearTimeout:()=>{}},{timeout:3000,filename:'standalone.html'});
assert(markup.includes('BATTLE LAB')&&markup.includes('Command center')&&markup.includes('sidebar'),'Standalone did not render desktop shell');
assert(!markup.includes('Battle Lab could not start'),'Standalone boot threw exception');
console.log('Standalone script, CSS and offline startup with disabled local storage: OK');
