import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('standalone.html','utf8');
const index=fs.readFileSync('index.html','utf8');
const fixtures=fs.readFileSync('src/mock-data.js','utf8').replaceAll('export const ','const ');
const replay=fs.readFileSync('src/replay-simulation.js','utf8').replaceAll(/^export function /gm,'function ');
const logic=fs.readFileSync('src/main.js','utf8').replace(/^import .*?from '\.\/mock-data\.js';\n/,'').replace(/^import .*?from '\.\/replay-simulation\.js';\n/,'');
const css=fs.readFileSync('src/styles.css','utf8');
const match=html.match(/<script>([\s\S]*?)<\/script>/);
assert(match,'Standalone is missing embedded JavaScript');
const embedded=match[1];
assert.equal(embedded,fixtures+'\n'+replay+'\n'+logic.replaceAll('</script>','<\\/script>'),'Standalone embedded JavaScript is incomplete or differs from source');
assert(html.includes('<style>'+css+'</style>'),'Embedded CSS incomplete');
assert(html.includes('boot-fallback'),'Error fallback missing');
assert(embedded.trimEnd().endsWith('}'),'Missing end of boot script');
new vm.Script(embedded,{filename:'standalone.html'});
let innerHTML='';
const root={set innerHTML(value){innerHTML=value},get innerHTML(){return innerHTML}};
const document={getElementById:id=>id==='app'?root:null,querySelector:()=>null,querySelectorAll:()=>[],addEventListener:()=>{},createElement:()=>({})};
const storage={getItem(){throw new Error('Storage blocked')},setItem(){throw new Error('Storage blocked')},removeItem(){throw new Error('Storage blocked')}};
vm.runInNewContext(embedded,{document,localStorage:storage,console,structuredClone,setTimeout:()=>0,clearTimeout:()=>{}},{timeout:3000,filename:'standalone.html'});
assert(innerHTML.includes('BATTLE LAB')&&innerHTML.includes('Command center')&&innerHTML.includes('sidebar'),'Standalone did not render the desktop shell');
assert(!innerHTML.includes('Battle Lab could not start'),'Standalone encountered a startup exception');
console.log('Standalone embedded assets, syntax, and offline boot (blocked storage): OK');
