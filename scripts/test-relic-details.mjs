import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {heroes,equipment,equipmentSets,equipmentSlots,resources,squads,opponents,battles,recipes,relics,formatNum} from '../src/mock-data.js';
const storage=new Map();
const document={getElementById:()=>({innerHTML:''}),querySelector:()=>null,querySelectorAll:()=>[],createElement:()=>({}),addEventListener:()=>{}};
const context=vm.createContext({heroes,equipment,equipmentSets,equipmentSlots,resources,squads,opponents,battles,recipes,relics,formatNum,document,
  localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)},structuredClone,clearTimeout,setTimeout:()=>0,console});
const source=fs.readFileSync(new URL('../src/main.js',import.meta.url),'utf8').split('\n').slice(1).join('\n').replace(/^import .*?from '\.\/replay-simulation\.js';\n/,'').replace(/\nrender\(\);\s*$/,'');
vm.runInContext(source,context);
const ev=code=>vm.runInContext(code,context);
const lion=relics.find(x=>x.id==='guardian-lion');
assert(lion,'Guardian Lion fixture missing');
assert.equal(lion.level,10); assert.equal(lion.maxLevel,10); assert.equal(lion.stars,5);
assert.deepEqual(lion.stats.map(x=>[x.label,x.value]),[['ATK',46],['DEF',138]]);
assert.equal(lion.abilityName,'CLEANSE');assert.equal(lion.cooldownSeconds,9.6);
assert(lion.abilityDescription.includes('Immunity to being stunned'));
assert.equal(ev('state.selectedRelic'),'guardian-lion');
let html=ev('inventoryView("relics")');
assert(html.includes('split-view equipment-view relic-vault-view'));
assert(html.includes('data-relic="guardian-lion"'));
assert(html.includes('relic-detail-inspector'));
assert(html.includes('RELIC DETAILS')&&html.includes('CLEANSE')&&html.includes('9.60s cooldown'));
assert(html.includes('46')&&html.includes('138'));
assert(html.includes('10/10')&&html.includes('★★★★★'));
const insight=ev('relicDetailInspector(rel("insight"))');
assert(insight.includes('Stats not captured'));
assert(!insight.includes('ATK 46'));
assert(insight.includes('Skill power +18%'));
assert(insight.includes('Leonardo da Vinci')&&insight.includes('Nikola Tesla'));
assert(insight.includes('data-relic-user="leonardo"'));
ev("state.selectedRelic='insight';state.search='guardian'");
html=ev('inventoryView("relics")');
assert.equal(ev('state.selectedRelic'),'guardian-lion');
assert(!html.includes('data-relic="insight"'));
ev("state.search='no-such-relic'");
html=ev('inventoryView("relics")');
assert(html.includes('No relics match this search')&&html.includes('No relic selected'));
assert.equal(ev('state.selectedRelic'),'guardian-lion');
ev("state.search='';state.selectedRelic='serpent'");
html=ev('inventoryView("relics")');
assert(html.includes('aria-selected="true"')&&html.includes('Serpent Sigil'));
assert.equal(ev('state.selectedRelic'),'serpent');
assert.equal(ev('changedHeroes().length'),0,'Opening a read-only inventory must not edit heroes');
console.log('Relic Vault side inspector, selected row, reference values, missing-data state, users, search and draft isolation: OK');
